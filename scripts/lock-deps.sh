#!/usr/bin/env bash
# Regenerate the pinned lock files from the *.in files.
#
#   scripts/lock-deps.sh
#
# Run after changing a *.in file, airflow/requirements.txt, or
# AIRFLOW_VERSION in airflow/Dockerfile, and commit the results. Needs uv.
set -euo pipefail

cd "$(dirname "$0")/.."

# Both pins come from the Airflow image
AIRFLOW_VERSION=$(sed -n 's/^ARG AIRFLOW_VERSION=//p' airflow/Dockerfile)
PYTHON_VERSION=$(sed -n 's/^ARG PYTHON_VERSION=//p' airflow/Dockerfile)
CONSTRAINTS="https://raw.githubusercontent.com/apache/airflow/constraints-${AIRFLOW_VERSION}/constraints-${PYTHON_VERSION}.txt"

compile() {
  uv pip compile --quiet --python-version "$PYTHON_VERSION" \
    --no-header --annotation-style line "$@"
}

# Same versions as the Airflow image, which installs with these constraints
{
  echo "# Generated by scripts/lock-deps.sh from requirements-dev.in against"
  echo "# Airflow ${AIRFLOW_VERSION} constraints, Python ${PYTHON_VERSION}. Do not edit."
  compile requirements-dev.in -c "$CONSTRAINTS"
} > requirements-dev.txt

# dbt + SQLFluff resolved together first; the image's dbt venv is then
# constrained to the same versions, so CI builds with exactly that dbt
{
  echo "# Generated by scripts/lock-deps.sh from requirements-dbt-ci.in. Do not edit."
  compile requirements-dbt-ci.in
} > requirements-dbt-ci.txt

{
  echo "# Generated by scripts/lock-deps.sh from requirements-dbt.in. Do not edit."
  compile airflow/requirements-dbt.in -c requirements-dbt-ci.txt
} > airflow/requirements-dbt.txt
